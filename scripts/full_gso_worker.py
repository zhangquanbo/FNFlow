"""Blender worker: new five-angle GSO data, fixed family split, test sealed, no model inference."""
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT));sys.dont_write_bytecode=True
import hashlib,json,math
import numpy as np
from src.research_io import write_json,sha256,now
from scripts import render_gso_holdout_blender as core

def main():
    out=ROOT/'outputs/gso_multielevation_fresh_20261026';out.mkdir(parents=True,exist_ok=True)
    intake=ROOT/'outputs/P1_gso_intake_v1/manifest_private.json';manifest=json.loads(intake.read_text())
    protocol=json.loads((ROOT/'configs/gso_boundary_material_review4.json').read_text())
    registration={'source_manifest_sha256':sha256(intake),'worker_sha256':sha256(__file__),
                  'core_sha256':sha256(ROOT/'scripts/render_gso_holdout_blender.py'),'angles':[0,15,30,45,60],
                  'jitter':'+/-2 degrees, hash gso-multielevation-v2/object/azimuth; no jitter at30',
                  'source_split':'fresh reconstruction from fixed name-family rule; no exact historical RGB reuse claim',
                  'test_sealed':True,'model_inference':False,'lighting':'original two-area-light/world recipe; matched Arb-style diagnostic is not generated by this step'}
    path=out/'preregistration.json'
    if path.exists():
        if json.loads(path.read_text())!=registration:raise RuntimeError('Frozen rendering protocol changed')
    else:write_json(path,registration)
    original_pose=core.camera_pose
    for split in ('val','test'):
        records=[];assets=sorted([r for r in manifest['records'] if r['split']==split],key=lambda r:r['name'])
        for i,asset in enumerate(assets):
            for pitch in (0,15,30,45,60):
                def pose(azimuth):
                    key=f'gso-multielevation-v2/{asset["name"]}/{int(azimuth)}'
                    jitter=0 if pitch==30 else int(hashlib.sha256(key.encode()).hexdigest()[:8],16)/(2**32-1)*4-2
                    return original_pose(azimuth,pitch+jitter)
                core.camera_pose=pose
                target=ROOT/'data/gso_multielevation_fresh_20261026'/f'pitch_{pitch:02d}'
                new=core.render_asset(asset,target,'CPU',protocol)
                for row in new:
                    view=int(row['image_key'].rsplit('/',1)[1])
                    with np.load(row['path']) as z:
                        actual=float(np.degrees(np.arctan2(z['camera_to_world'][2,3],np.hypot(*z['camera_to_world'][:2,3]))))
                        if abs(actual-pitch)>2.001 or not z['valid'].any():raise RuntimeError('GSO pitch/validity failure')
                    records.append({**row,'image_key':f'gso_fresh/{asset["name"]}/pitch{pitch:02d}/{view}','elevation_bin':pitch,'elevation_actual':actual})
            write_json(out/(split+'_progress.json'),{'status':'rendering','assets':i+1,'total_assets':len(assets),'images':len(records),'updated_at':now()})
            print('GSO',split,i+1,'/',len(assets),'images',len(records),flush=True)
        if len(records)!=len(assets)*20:raise RuntimeError('Missing GSO views')
        mp=ROOT/'data/gso_multielevation_fresh_20261026'/split/'private_manifest.json'
        write_json(mp,{'records':records,'split':split,'training_allowed':False,'test_sealed':split=='test','registration_sha256':sha256(path)})
        write_json(out/(split+'_summary.json'),{'status':'completed','assets':len(assets),'images':len(records),'manifest':str(mp),'manifest_sha256':sha256(mp),'test_sealed':split=='test','scores_computed':False})
    write_json(out/'status.json',{'status':'completed','test_sealed':True,'scores_computed':False,'updated_at':now()})

if __name__=='__main__':main()
